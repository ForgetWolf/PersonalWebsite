"""Build the independent Russian SVG from GOST skeleton coordinates.

Python is an authoring tool only; the website uses C++ CGI and native SVG.
No CoffeeScript is executed. Original paths are converted from relative to
absolute coordinates without smoothing or changing their geometry.
"""
from pathlib import Path
import json
import math
import re
from html import escape

ROOT = Path(__file__).resolve().parent
cfg = json.loads((ROOT / "languages/ru.json").read_text(encoding="utf-8"))
source = (ROOT / cfg["font_file"]).read_text(encoding="utf-8")
glyphs = {char: (path, float(width)) for char, path, width in re.findall(
    r'^    "([^"\n]+)":\s*\n\s*d: "([^"]*)"\s*\n\s*w: (-?[\d.]+)',
    source, re.M)}


def split_strokes(path):
    # The selected GOST glyphs contain relative moveto/lineto commands only.
    if re.sub(r'[ml\s,\d.\-]', '', path):
        raise ValueError("Unexpected GOST path command")
    x = y = 0.0
    current = []
    result = []
    for command, dx, dy in re.findall(r'([ml])\s*(-?[\d.]+),(-?[\d.]+)', path):
        x += float(dx)
        y += float(dy)
        if command == 'm':
            if len(current) > 1:
                result.append(current)
            current = [(x, y)]
        else:
            current.append((x, y))
    if len(current) > 1:
        result.append(current)
    return result


strokes = []
points = []
advance = 0.0
for char in cfg["text"]:
    if char == ' ':
        advance += 4.375
        continue
    if char not in glyphs:
        raise ValueError(f"GOST glyph not found: {char}")
    path, width = glyphs[char]
    for coords in split_strokes(path):
        coords = [(x + advance, y) for x, y in coords]
        length = sum(math.dist(a, b) for a, b in zip(coords, coords[1:]))
        if length > 0:
            strokes.append((coords, length))
            points.extend(coords)
    advance += width + 1.875

left = min(x for x, y in points) - 2
top = min(y for x, y in points) - 2
width = max(x for x, y in points) - left + 2
height = max(y for x, y in points) - top + 2
total = cfg['total_seconds']
fade_start = total - cfg['fade_out']
write_end = fade_start - cfg['hold']
draw_seconds = write_end - cfg['initial_wait'] - cfg['pen_lift'] * (len(strokes) - 1)
if draw_seconds <= 0:
    raise ValueError("Insufficient time for strokes")
speed = sum(length for _, length in strokes) / draw_seconds
text = escape(cfg['text'], quote=True)
svg = [f'''<svg xmlns="http://www.w3.org/2000/svg" width="100%" height="95vh"
    role="img" aria-label="{text}">
<metadata>GOST skeletal font by peko, based on GOST 2.304-81.
Source: https://github.com/peko/GOST-FONT
Original coordinate geometry preserved; no glyph smoothing.</metadata>
<svg x="10%" y="35%" width="80%" height="30%"
    viewBox="{left:g} {top:g} {width:g} {height:g}" preserveAspectRatio="xMidYMid meet">
<g fill="none" stroke="CanvasText" stroke-width="0.24"
    stroke-linecap="round" stroke-linejoin="round" opacity="0">
<animate attributeName="opacity" from="0" to="1" begin="{cfg['initial_wait']:.5f}s"
    dur="{cfg['fade_in']:.5f}s" fill="freeze"/>
<animate attributeName="opacity" from="1" to="0" begin="{fade_start:.5f}s"
    dur="{cfg['fade_out']:.5f}s" fill="freeze"/>''']
time = cfg['initial_wait']
for coords, length in strokes:
    d = ' '.join(('M' if i == 0 else 'L') + f'{x:g},{y:g}'
                 for i, (x, y) in enumerate(coords))
    duration = length / speed
    svg.append(f'''<path d="{d}" pathLength="1" stroke-dasharray="1 1"
    stroke-dashoffset="1" visibility="hidden">
<set attributeName="visibility" to="visible" begin="{time:.5f}s" fill="freeze"/>
<animate attributeName="stroke-dashoffset" from="1" to="0" begin="{time:.5f}s"
    dur="{duration:.5f}s" calcMode="linear" fill="freeze"/>
</path>''')
    time += duration + cfg['pen_lift']
svg.append('</g></svg></svg>')
(ROOT / 'russian.hpp').write_text(
    '// Generated by generate_russian.py from languages/ru.json and GOST-font.coffee\n'
    '#pragma once\ninline constexpr const char* russian_label = u8"' + cfg['text'] + '";\n'
    'inline constexpr const char* russian_svg = u8R"RUSSIAN(\n' + '\n'.join(svg)
    + '\n)RUSSIAN";\n', encoding='utf-8')
print(f"Russian: {len(strokes)} strokes, writing ends {write_end:.3f}s; "
      f"hold {cfg['hold']}s, fade ends {total:.3f}s")
