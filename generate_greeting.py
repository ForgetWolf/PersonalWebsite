"""Development helper: convert original Hershey strokes to an animated SVG header.

Run with Python 3 only when changing the greeting. Runtime needs C++ only.
"""
from pathlib import Path
import json
import math
import re
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parent
cfg = json.loads((ROOT / "languages/en.json").read_text(encoding="utf-8"))
TEXT = cfg['text']
font = ET.parse(ROOT / "HersheyScript1.svg").getroot()
ns = {"s": "http://www.w3.org/2000/svg"}
glyphs = {g.get("unicode"): g for g in font.findall(".//s:glyph", ns)}
strokes = []
advance = 0.0
points = []
for char in TEXT:
    glyph = glyphs[char]
    for part in re.findall(r"M[^M]+", glyph.get("d", "")):
        numbers = [float(n) for n in re.findall(r"-?\d+(?:\.\d+)?", part)]
        coords = list(zip(numbers[::2], numbers[1::2]))
        length = sum(math.dist(a, b) for a, b in zip(coords, coords[1:]))
        if length > 0:
            strokes.append((advance, part.strip(), length, char))
            points.extend((x + advance, -y) for x, y in coords)
    advance += float(glyph.get("horiz-adv-x", "378"))

left = min(x for x, y in points) - 160
top = min(y for x, y in points) - 160
width = max(x for x, y in points) - left + 160
height = max(y for x, y in points) - top + 160
pause = cfg['pen_lift']
# Keep the previous full timeline length, reserving hold/fade inside it.
fade_start = cfg['total_seconds'] - cfg['fade_out']
write_end = fade_start - cfg['hold']
draw_seconds = write_end - cfg['initial_wait'] - pause * (len(strokes) - 1)
if draw_seconds <= 0:
    raise ValueError("Insufficient time for strokes")
speed = sum(s[2] for s in strokes) / draw_seconds
metadata = font.find("s:metadata", ns).text
svg = [f'''<svg xmlns="http://www.w3.org/2000/svg" width="100%" height="95vh"
    role="img" aria-label="{TEXT}">
<metadata>{metadata}</metadata>
<svg x="10%" y="35%" width="80%" height="30%"
    viewBox="{left:g} {top:g} {width:g} {height:g}" preserveAspectRatio="xMidYMid meet">
<g fill="none" stroke="CanvasText" stroke-width="17" stroke-linecap="round" stroke-linejoin="round" opacity="0">
<animate attributeName="opacity" from="0" to="1" begin="{cfg['initial_wait']:.5f}s"
    dur="{cfg['fade_in']:.5f}s" fill="freeze"/>
<animate attributeName="opacity" from="1" to="0" begin="{fade_start:.5f}s"
    dur="{cfg['fade_out']:.5f}s" fill="freeze"/>''']
time = cfg['initial_wait']
for x, path, length, char in strokes:
    duration = length / speed
    svg.append(f'''<path transform="translate({x:g} 0) scale(1 -1)" d="{path}"
    pathLength="1" stroke-dasharray="1 1" stroke-dashoffset="1" visibility="hidden">
<set attributeName="visibility" to="visible" begin="{time:.5f}s" fill="freeze"/>
<animate attributeName="stroke-dashoffset" from="1" to="0" begin="{time:.5f}s"
    dur="{duration:.5f}s" calcMode="linear" fill="freeze"/>
</path>''')
    time += duration + pause
svg.append("</g></svg></svg>")
result = "\n".join(svg)
(ROOT / "greeting.hpp").write_text(
    '// Generated by generate_greeting.py; original font acknowledgements embedded.\n'
    '#pragma once\ninline constexpr const char* greeting_svg = R"GREETING(\n'
    + result + '\n)GREETING";\n', encoding="utf-8")
print(f"English: {len(strokes)} original strokes; writing ends {time-pause:.3f}s; "
      f"fade ends {cfg['total_seconds']:.3f}s")
